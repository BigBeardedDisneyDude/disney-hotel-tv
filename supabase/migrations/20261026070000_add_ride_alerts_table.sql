-- Favorite-ride wait alerts: one row per device + ride + threshold.
--
-- The client (predict.html / wdwpredict.html via predict-core.js) subscribes
-- to Web Push in the browser, then upserts the subscription object plus a
-- threshold ("alert me below N minutes") here directly with the anon key —
-- same trust model already used for wait_times/conversations in this project.
--
-- collect-waits (which already fetches every ride's live wait every 15 min)
-- reads this table with the service role key, checks threshold crossings
-- against the wait it already has in memory, and sends the push via
-- web-push. last_state is a one-ping-per-crossing latch: it only fires when
-- a ride goes from 'above' to 'below', not on every check while it stays
-- under the threshold.
--
-- endpoint is the push subscription's unique URL — doubles as this table's
-- per-device identity since there's no real auth system here. The unique
-- constraint means re-enabling an alert for a ride you already have one on
-- (e.g. changing the threshold) upserts in place rather than duplicating.

create table if not exists public.ride_alerts (
  id bigint generated by default as identity primary key,
  endpoint text not null,
  subscription jsonb not null,
  park text not null,
  ride_id text not null,
  threshold_minutes smallint not null,
  last_state text not null default 'above' check (last_state in ('above', 'below')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (endpoint, park, ride_id)
);

create index if not exists idx_ride_alerts_park on public.ride_alerts (park);

alter table public.ride_alerts enable row level security;

-- Anon key manages its own device's rows directly from the browser (no
-- Edge Function in the write path) — same permissive-anon pattern as
-- wait_times/conversations elsewhere in this project. collect-waits reads
-- and updates last_state with the service role key, which bypasses RLS.
create policy "anon can manage ride_alerts" on public.ride_alerts
  for all
  to anon
  using (true)
  with check (true);
